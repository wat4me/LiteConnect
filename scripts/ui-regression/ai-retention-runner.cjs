const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'liteconnect-ai-retention-'))
app.setPath('userData', path.join(artifacts, 'profile'))
const timeout = setTimeout(() => { console.error('AI retention UI timed out', { artifacts }); app.exit(1) }, 120_000)
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1100, height: 900, webPreferences: { contextIsolation: true, backgroundThrottling: false } })
  const run = code => window.webContents.executeJavaScript(code)
  const wait = async code => {
    const start = Date.now()
    while (!await run(code)) {
      if (Date.now() - start > 10_000) throw new Error(`Timeout: ${code}`)
      await new Promise(resolve => setTimeout(resolve, 30))
    }
  }
  const card = '.ai-image-composer-fixture .ai-question-card'
  const input = value => run(`(() => {const text=document.querySelector('${card} textarea');text.value=${JSON.stringify(value)};text.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  const next = () => run(`document.querySelector('${card} .ai-question-next').click()`)
  const remount = async () => {
    await run('window.__uiRegression.closeImageComposer()')
    await wait(`!document.querySelector('${card}')`)
    await run('window.__uiRegression.openImageComposer()')
    await wait(`!!document.querySelector('${card}')`)
  }
  await window.loadURL(process.env.LITECONNECT_UI_TEST_URL)
  await wait('!!window.__uiRegression')
  await run('window.__uiRegression.openImageComposer()')
  await wait(`!!document.querySelector('.ai-image-composer-fixture .composer-input')`)
  await run('window.__uiRegression.resetQuestion(true);window.__uiRegression.showIntegratedQuestion(true)')
  await wait(`!!document.querySelector('${card}')`)
  await run(`document.querySelector('${card} .ai-question-content input').click()`)
  await input('只读检查')
  await next()
  await wait(`document.querySelector('${card} .ai-question-page').textContent.trim()==='2 / 3'`)
  await run(`document.querySelector('${card} .ai-question-content input').click();document.querySelector('${card} .ai-question-custom input').click()`)
  await input('特别关注日志')
  await run(`document.querySelector('.ai-image-composer-fixture .ai-conversation-menu-trigger').click()`)
  await wait(`!!document.querySelector('.ai-conversation-menu [data-action="history"]')`)
  await run(`document.querySelector('.ai-conversation-menu [data-action="history"]').click()`)
  await wait(`!!document.querySelector('.ai-image-composer-fixture .ai-history-page')`)
  await run('window.__uiRegression.openImageComposer()')
  await wait(`!document.querySelector('.ai-image-composer-fixture .ai-history-page') && !!document.querySelector('${card}')`)
  assert.equal(await run(`document.querySelector('${card} textarea').value`), '特别关注日志', 'Reopening pending work reveals the answer form over a previously open history panel without losing its draft')
  await remount()
  assert.ok(await run(`document.querySelector('${card} .ai-question-page').textContent.trim()==='2 / 3' && document.querySelector('${card} textarea').value==='特别关注日志' && document.querySelectorAll('${card} input:checked').length===2`), 'Remount restores page, multi-choice, custom selection and text')
  await run(`document.querySelector('${card} .ai-question-previous').click()`)
  await wait(`document.querySelector('${card} textarea').value==='只读检查'`)
  assert.equal(await run(`document.querySelector('${card} .ai-question-content input').checked`), true)
  await next()
  await run(`window.__uiRegression.switchImageSession('other-fixture')`)
  await wait(`!document.querySelector('${card}')`)
  await run('window.__uiRegression.showIntegratedQuestion(true)')
  await wait(`!!document.querySelector('${card}')`)
  assert.ok(await run(`document.querySelector('${card} .ai-question-page').textContent.trim()==='1 / 3' && document.querySelector('${card} textarea').value==='' && !document.querySelector('${card} input:checked')`), 'Another session cannot inherit the same tool id draft')
  await run(`window.__uiRegression.switchImageSession('image-fixture')`)
  await wait(`document.querySelector('${card} .ai-question-page')?.textContent.trim()==='2 / 3'`)
  assert.equal(await run(`document.querySelector('${card} textarea').value`), '特别关注日志')
  await next()
  await input('检查昨晚')
  await run(`window.__uiRegression.setQuestionSubmissionRejected(true);document.querySelector('${card} button[type="submit"]').click()`)
  await wait(`!!document.querySelector('${card} .ai-question-error')`)
  await remount()
  assert.equal(await run(`document.querySelector('${card} textarea').value`), '检查昨晚', 'Failed submission keeps its draft across remounts')
  await run(`window.__uiRegression.setQuestionSubmissionRejected(false);document.querySelector('${card} button[type="submit"]').click()`)
  await wait(`!document.querySelector('${card}') && window.__uiRegression.questionDraftCount()===0`)
  assert.equal(await run('window.__uiRegression.getQuestionAnswers().length'), 1, 'Restoring a draft never submits automatically')
  await run('window.__uiRegression.resetQuestion(false);window.__uiRegression.showIntegratedQuestion(true)')
  await wait(`!!document.querySelector('${card}')`)
  await input('跳过前的草稿')
  await run(`document.querySelector('${card} .ai-question-skip').click()`)
  await wait('window.__uiRegression.questionDraftCount()===0')
  await run('window.__uiRegression.resetQuestion(false);window.__uiRegression.showIntegratedQuestion(true)')
  await wait(`!!document.querySelector('${card}')`)
  await input('后台结束前的草稿')
  await run('window.__uiRegression.closeImageComposer();window.__uiRegression.finishIntegratedQuestion()')
  await wait('window.__uiRegression.questionDraftCount()===0')

  await run('window.__uiRegression.aiLazyWorkspace(20)')
  await wait(`document.querySelectorAll('.ai-fixture .workspace-response-host').length===20`)
  assert.equal(await run(`document.querySelectorAll('.ai-fixture .workspace-response-host .markdown-block').length`), 0, 'Collapsed hosts create no Markdown content nodes')
  assert.equal(await run(`document.querySelectorAll('.ai-fixture .workspace-response-host pre').length`), 0)
  const collapsedNodes = await run(`document.querySelector('.ai-fixture').querySelectorAll('*').length`)
  await run(`document.querySelector('.ai-fixture .workspace-response-host summary').click()`)
  await wait(`document.querySelectorAll('.ai-fixture .workspace-response-host table').length===30`)
  assert.equal(await run(`document.querySelectorAll('.ai-fixture .workspace-response-host:not([open]) .ai-streaming-markdown').length`), 0, 'Only the opened host is parsed and mounted')
  await run(`document.querySelector('.ai-fixture .workspace-response-host .copy-btn').click()`)
  await wait(`window.__uiRegression.calls.clipboardWrites.at(-1)==='systemctl status app'`)
  assert.equal(await run(`document.querySelectorAll('.ai-fixture .workspace-response-host .code-action-btn').length`), 0, 'Workspace code offers copying without terminal execution actions')
  const expandedNodes = await run(`document.querySelector('.ai-fixture').querySelectorAll('*').length`)
  await run(`document.querySelector('.ai-fixture .workspace-response-host summary').click()`)
  await wait(`document.querySelectorAll('.ai-fixture .workspace-response-host pre').length===0`)
  assert.equal(await run(`document.querySelector('.ai-fixture').querySelectorAll('*').length`), collapsedNodes, 'Closing releases the host content nodes')
  await run(`document.querySelector('.ai-fixture .workspace-response-host summary').click()`)
  await wait(`document.querySelectorAll('.ai-fixture .workspace-response-host table').length===30`)

  await run('window.__uiRegression.aiDisclosure()')
  await wait(`!!document.querySelector('.ai-fixture .reasoning-box') && !!document.querySelector('.ai-fixture .tool-run')`)
  await run(`document.querySelector('.ai-fixture .reasoning-box summary').click();document.querySelector('.ai-fixture .tool-run summary').click()`)
  await wait(`!!document.querySelector('.ai-fixture .reasoning-content') && !!document.querySelector('.ai-fixture .tool-run-section')`)
  await run('window.__uiRegression.aiDisclosure(false)')
  await wait(`!document.querySelector('.ai-fixture .tool-run')`)
  await run('window.__uiRegression.aiDisclosure()')
  await wait(`!!document.querySelector('.ai-fixture .tool-run')`)
  assert.ok(await run(`!document.querySelector('.ai-fixture .reasoning-content') && !document.querySelector('.ai-fixture .tool-run-section')`), 'Removed message parts do not resurrect obsolete expansion choices')
  await run(`document.querySelector('.ai-fixture .reasoning-box summary').click();document.querySelector('.ai-fixture .tool-run summary').click()`)
  await wait(`!!document.querySelector('.ai-fixture .tool-run-section')`)
  await run(`window.__uiRegression.setAiConversationKey('different-thread')`)
  await wait(`!document.querySelector('.ai-fixture .reasoning-content') && !document.querySelector('.ai-fixture .tool-run-section')`)
  assert.equal(await run('window.__uiError || null'), null)
  console.log(JSON.stringify({ passed: true, collapsedNodes, expandedNodes, hosts: 20, blocksPerHost: 30,
    flows: ['question remount', 'session isolation', 'failed submission retention', 'successful submit cleanup', 'skip cleanup', 'offscreen completion cleanup', 'lazy host Markdown', 'deleted disclosure cleanup', 'thread isolation'], artifacts }))
  clearTimeout(timeout); window.destroy(); app.quit()
}).catch(error => { console.error(error, { artifacts }); clearTimeout(timeout); app.exit(1) })
