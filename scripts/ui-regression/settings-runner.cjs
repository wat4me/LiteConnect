const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const artifacts = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'liteconnect-settings-ui-'))
app.setPath('userData', path.join(artifacts, 'profile'))
let window, stage = 'loading'
const timeout = setTimeout(() => { console.error({ stage, artifacts }); app.exit(1) }, 180_000)
app.whenReady().then(async () => {
  window = new BrowserWindow({ show: false, frame: false, width: 1200, height: 850, webPreferences: { contextIsolation: true, backgroundThrottling: false } })
  window.webContents.debugger.attach('1.3')
  const run = source => window.webContents.executeJavaScript(source)
  const wait = async expression => {
    const deadline = Date.now() + 15000
    while (!await run(expression)) { if (Date.now() > deadline) throw new Error(`Timeout: ${expression}`); await new Promise(resolve => setTimeout(resolve, 30)) }
  }
  const click = selector => run(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const input = (selector, value) => run(`(() => {const el=document.querySelector(${JSON.stringify(selector)});el.focus();el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('input',{bubbles:true}));})()`)
  await window.loadURL(process.env.LITECONNECT_UI_TEST_URL + '?failSettings=1')
  await wait('!!window.__settings && !!document.querySelector(".settings-load-error")')
  assert.equal(await run('!!document.querySelector(".settings-fields")'), false, 'A failed read never presents default draft controls as loaded settings')
  assert.equal(await run('document.querySelector(".settings-footer .ui-btn-primary").disabled'), true)
  assert.equal(await run('window.__settings.tryClose()'), 1, 'The user can leave a failed loading screen')
  await run('window.__settings.resetCloses()')
  await click('.settings-load-error button')
  await wait('!!window.__settings && !!document.querySelector(".db-window-advanced")')
  assert.equal(await run('document.querySelector(".db-window-advanced").open'), false, 'Window preference starts collapsed')
  stage = 'settings search reveals advanced options'
  await input('.nav-search-input', '分离')
  await wait('!!document.querySelector(".nav-search-hit")')
  await run('document.querySelector(".nav-search-hit").dispatchEvent(new MouseEvent("mousedown", {bubbles:true,cancelable:true}))')
  await wait('document.querySelector(".db-window-advanced")?.open')
  await run('(() => {const el=document.querySelector(".db-window-advanced select");el.value="currentWindow";el.dispatchEvent(new Event("change",{bubbles:true}));})()')
  await click('.settings-footer .ui-btn-primary')
  await wait('window.__settings.saved().dbOpenMode==="currentWindow"')
  stage = 'monitor setting saves and closes its panel'
  await run('document.querySelectorAll(".nav-list .nav-item")[5].click()')
  await wait('!!document.querySelector("[data-setting=\\"network.monitor\\"]")')
  await run('window.__settings.openMonitor()')
  await click('[data-setting="network.monitor"] + .toggle-row button')
  await click('.settings-footer .ui-btn-primary')
  await wait('!window.__settings.state().enabled && !window.__settings.state().open')
  assert.equal(await run('!!document.querySelector(".left-toolbar button[aria-pressed=true]")'), false)
  assert.equal(await run('document.querySelectorAll(".left-toolbar button").length'), 6, 'Monitor entry disappears without removing other tools')
  await click('[data-setting="network.monitor"] + .toggle-row button')
  await click('.settings-footer .ui-btn-primary')
  await wait('window.__settings.state().enabled')
  assert.equal(await run('document.querySelectorAll(".left-toolbar button").length'), 7)
  stage = 'remote-window settings sync'
  await run('window.__settings.openMonitor();window.__settings.remote(false)')
  await wait('!window.__settings.state().enabled && !window.__settings.state().open')
  await run('window.__settings.remote(true)')
  await run('document.querySelectorAll(".nav-list .nav-item")[4].click()')
  await wait('!!document.querySelector(".db-window-advanced")')
  await click('.db-window-advanced summary')
  stage = 'saving only edited fields while another window changed the configuration'
  await run('window.__settings.mutateStored({x11AutoStartEnabled:false,monitorIntervalMs:9000,theme:"light"});window.__settings.holdSave()')
  const size = await run('window.__settings.saved().dbFontSize')
  await click('[data-setting="database.fontSize"] + .font-size-row button:last-child')
  await run('window.__settings.remoteSnapshot({terminalFontSize:18,dbPageSize:200,dbFontSize:19},["terminalFontSize","dbPageSize","dbFontSize"])')
  assert.equal(await run('document.querySelector("[data-setting=\\"database.pageSize\\"] + select").value'), '200')
  assert.equal(await run('document.querySelector("[data-setting=\\"database.fontSize\\"] + .font-size-row span").textContent.trim()'), `${size + 1}px`, 'An incoming commit preserves this page\'s edited font size')
  await click('.settings-footer .ui-btn-primary')
  await wait('document.querySelector(".settings-fields").disabled')
  assert.equal(await run('window.__settings.tryClose()'), 0, 'Module navigation cannot discard settings while a save is in progress')
  assert.equal(await run('document.querySelector(".db-window-advanced select").matches(":disabled")'), true)
  await run('window.__settings.releaseSave()')
  await wait('!document.querySelector(".settings-fields").disabled')
  assert.deepEqual(await run('window.__settings.patches().at(-1)'), { dbFontSize: size + 1 })
  assert.equal(await run('window.__settings.saved().x11AutoStartEnabled'), false)
  assert.equal(await run('window.__settings.saved().monitorIntervalMs'), 9000)
  assert.equal(await run('window.__settings.saved().theme'), 'light')
  let layouts = 0
  for (const locale of ['zh-CN', 'en-US']) for (const theme of ['light', 'dark', 'eyecare']) for (const width of [760, 1200]) {
    stage = `${locale}/${theme}/${width}`
    await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width, height: 850, deviceScaleFactor: 1, mobile: false })
    await run(`window.__settings.theme('${theme}','${locale}')`)
    await wait(`innerWidth===${width}`)
    assert.ok(await run(`(() => {const panel=document.querySelector('.settings-page');return panel.getBoundingClientRect().right<=innerWidth+1 && document.querySelector('.settings-stage').scrollWidth<=document.querySelector('.settings-stage').clientWidth+1})()`), stage)
    layouts++
  }
  await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width: 1200, height: 850, deviceScaleFactor: 1, mobile: false })
  await run(`window.__settings.theme('light','zh-CN')`)
  fs.writeFileSync(path.join(artifacts, 'database-settings.png'), (await window.webContents.capturePage()).toPNG())
  assert.equal(await run('window.__settingsError || null'), null)
  console.log(JSON.stringify({ passed: true, layouts, flows: ['failed read/retry/leave', 'advanced search/reveal/save', 'monitor hide/show and panel close', 'remote-window setting notification', 'dirty draft rebase', 'partial save preserves external changes', 'save-in-progress close guard'], artifacts }))
  clearTimeout(timeout); window.destroy(); app.quit()
}).catch(error => { console.error(error, { stage, artifacts }); clearTimeout(timeout); window?.destroy(); app.exit(1) })
