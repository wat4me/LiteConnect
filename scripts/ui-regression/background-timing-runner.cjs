const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'liteconnect-background-timing-'))
app.setPath('userData', path.join(artifacts, 'profile'))
let window
let lastAction = 'loading'
const timeout = setTimeout(() => { console.error('Background timing UI timed out', { artifacts, lastAction }); app.exit(1) }, 240_000)
app.whenReady().then(async () => {
  window = new BrowserWindow({ show: false, width: 1200, height: 900, webPreferences: { nodeIntegration: false, contextIsolation: true, backgroundThrottling: false } })
  const run = script => { lastAction = script.slice(0, 300); return window.webContents.executeJavaScript(script) }
  const wait = async expression => {
    const start = Date.now()
    while (!await run(expression)) {
      if (Date.now() - start > 10000) throw new Error(`Timeout: ${expression}`)
      await new Promise(resolve => setTimeout(resolve, 30))
    }
  }
  const settle = () => run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  const openTasks = async () => {
    await run(`(() => {const button=document.querySelector('.background-float-trigger');if(button.getAttribute('aria-expanded')!=='true')button.click()})()`)
    await wait(`!!document.querySelector('.background-popover')`)
    await wait(`!document.querySelector('.background-popover').getAnimations({subtree:true}).length`)
    await settle()
  }
  const panel = '.ai-image-composer-fixture'
  await window.loadURL(process.env.LITECONNECT_UI_TEST_URL)
  await wait('!!window.__uiRegression')
  await run('window.__uiRegression.openImageComposer()')
  await wait(`!!document.querySelector('${panel} .composer-input') && window.__uiRegression.calls.aiCreates.length===1`)
  const jobs = `[{jobId:'long-running',sessionId:'image-fixture',command:'find /var/log/application -type f -name very-long-command-and-arguments.log',status:'running',startedAt:Date.now()-65000},{jobId:'second-running',sessionId:'other-fixture',command:'inspect-other-host',status:'running',startedAt:Date.now()-5000},{jobId:'finished',sessionId:'image-fixture',command:'completed-command',status:'completed',startedAt:1000,finishedAt:125000,exitCode:0}]`
  for (const theme of ['light', 'dark', 'eyecare']) {
    await run(`window.__uiRegression.setTheme('${theme}')`)
    for (const [width, workspace] of [[300, false], [440, false], [440, true], [1000, true]]) {
      await run(`window.__uiRegression.setBackgroundJobs(${jobs})`)
      await run(`window.__uiRegression.setBackgroundLayout(${workspace})`)
      await run(`Object.assign(document.querySelector('${panel}').style,{width:'${width}px',height:'620px'})`)
      await wait(`document.querySelector('.ai-background-tasks')?.dataset.layout==='${workspace ? 'workspace' : 'sidebar'}'`)
      await run(`document.querySelector('${panel}').scrollIntoView({block:'start'})`)
      await openTasks()
      await settle()
      assert.equal(await run(`document.querySelectorAll('.background-task-body li').length`), workspace ? 3 : 2, 'Only jobs owned by the panel are shown')
      assert.ok(await run(`Array.from(document.querySelectorAll('.background-job-stop')).every(button=>button.querySelector('svg')&&button.getAttribute('aria-label').includes('停止后台任务')&&button.title&&button.textContent.trim()==='')`), 'Icon stop buttons keep descriptive labels and hover hints')
      assert.ok(await run(`document.querySelector('.background-heading-elapsed').textContent.includes('${workspace ? '最长' : '已运行'}')`), 'Collapsed heading identifies the running duration')
      assert.ok(await run(`(() => {const task=document.querySelector('.background-popover'),r=task.getBoundingClientRect();return task.scrollWidth<=task.clientWidth+1&&[...task.querySelectorAll('.background-job-elapsed,.background-job-stop,.tool-run-state')].every(node=>{const b=node.getBoundingClientRect();return b.right<=r.right&&b.left>=r.left})})()`), `${theme}/${width}/${workspace}: status, duration and stop controls fit`)
      const rows = await run(`(() => {const row=document.querySelector('.background-job summary');return {main:row.querySelector('.background-job-main').getBoundingClientRect().top,state:row.querySelector('.tool-run-outcome').getBoundingClientRect().top}})()`)
      assert.ok(rows.state > rows.main + 5, 'Floating task cards keep commands and actions on separate rows')
      assert.ok(await run(`(() => {const pop=document.querySelector('.background-popover').getBoundingClientRect(),body=document.querySelector('${panel} .ai-body').getBoundingClientRect(),composer=document.querySelector('${panel} .composer-area').getBoundingClientRect();return pop.left>=body.left&&pop.right<=body.right&&pop.top>=body.top&&pop.bottom<=composer.top})()`), 'Popover stays inside the chat and above the input')
      assert.equal(await run(`document.querySelector('.background-task-body li:last-child .background-job-elapsed').textContent`), '用时 02:04', 'Completed duration uses finish minus start')
      const rect = await run(`(() => {const r=document.querySelector('${panel}').getBoundingClientRect();return {x:Math.floor(r.x),y:Math.floor(r.y),width:Math.floor(r.width),height:Math.floor(r.height)}})()`)
      fs.writeFileSync(path.join(artifacts, `${theme}-${workspace ? 'workspace' : 'sidebar'}-${width}.png`), (await window.webContents.capturePage(rect)).toPNG())
    }
  }
  await run('window.__uiRegression.setBackgroundLayout(false)')
  assert.ok(await run(`!document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})`), 'The circle merges into the open card')
  await run(`document.querySelector('.background-heading-toggle').click()`)
  await wait(`!document.querySelector('.background-popover')`)
  assert.ok(await run(`document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})`), 'Closing the card restores the circle')
  const before = await run(`document.querySelector('.background-float-trigger').title`)
  const network = await run('JSON.stringify(window.__uiRegression.backgroundNetworkCalls)')
  await wait(`document.querySelector('.background-float-trigger').title!==${JSON.stringify(before)}`)
  assert.equal(await run('JSON.stringify(window.__uiRegression.backgroundNetworkCalls)'), network, 'Elapsed display ticks without get_job or list polling')
  await openTasks()
  const finishedBefore = await run(`document.querySelector('.background-task-body li:last-child .background-job-elapsed').textContent`)
  assert.equal(finishedBefore, '用时 02:04', 'A finished task stays fixed while other tasks continue')
  await run('window.__uiRegression.setBackgroundLayout(false,false)')
  const paused = await run(`document.querySelector('.background-float-trigger').title`)
  assert.ok(await run(`!document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})&&!document.querySelector('.background-popover')`), 'Leaving AI hides the icon and dismisses its popover')
  await run('new Promise(resolve=>setTimeout(resolve,1200))')
  assert.equal(await run(`document.querySelector('.background-float-trigger').title`), paused, 'Inactive panels pause their local clock')
  await run('window.__uiRegression.setBackgroundLayout(false,true)')
  assert.notEqual(await run(`document.querySelector('.background-float-trigger').title`), paused, 'Returning to a panel catches up from actual start time')
  await openTasks()
  await run(`document.querySelector('.background-job-stop').click()`)
  await wait(`document.querySelector('.background-task-body li[data-status="stopped"]')`)
  assert.equal(await run(`document.querySelector('.background-job').open`), false, 'Clicking the stop icon does not toggle task details')
  await run(`window.__uiRegression.setBackgroundJobs(['completed','failed','cancelled','timeout'].map((status,index)=>({jobId:'ended-'+index,sessionId:'image-fixture',command:status,status,startedAt:1000,finishedAt:125000,exitCode:status==='completed'?0:1})))`)
  await wait(`!document.querySelector('.background-heading-elapsed')`)
  const ended = await run(`Array.from(document.querySelectorAll('.background-job-elapsed')).map(node=>node.textContent)`)
  assert.deepEqual(ended, Array(4).fill('用时 02:04'), 'Success, failure, cancellation and timeout all freeze on completion')
  await run('new Promise(resolve=>setTimeout(resolve,1200))')
  assert.deepEqual(await run(`Array.from(document.querySelectorAll('.background-job-elapsed')).map(node=>node.textContent)`), ended, 'Terminal durations do not continue counting')
  assert.ok(await run(`!!document.querySelector('.background-float-attention')&&!document.querySelector('.background-float-count')`), 'Failures retain an attention dot after running jobs end')
  await run(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}))`)
  await wait(`!document.querySelector('.background-popover')`)
  assert.ok(await run(`document.activeElement===document.querySelector('.background-float-trigger')`), 'Escape returns focus to the icon')

  // Use real pointer input to verify capture, drag threshold, snapping and click suppression.
  window.webContents.debugger.attach('1.3')
  const mouse = (type, x, y, extra = {}) => window.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type, x, y, ...extra })
  const geometry = () => run(`(() => {const a=document.querySelector('.ai-background-tasks').getBoundingClientRect(),b=document.querySelector('.background-float-trigger').getBoundingClientRect();return {left:a.left,top:a.top,right:a.right,bottom:a.bottom,x:b.x+b.width/2,y:b.y+b.height/2}})()`)
  let area = await geometry()
  await mouse('mousePressed', area.x, area.y, { button: 'left', buttons: 1, clickCount: 1 })
  await mouse('mouseMoved', area.left + 20, area.top + 35, { button: 'left', buttons: 1 })
  await mouse('mouseReleased', area.left + 20, area.top + 35, { button: 'left', buttons: 0, clickCount: 1 })
  await settle()
  assert.equal(await run(`!!document.querySelector('.background-popover')`), false, 'Dragging does not open the panel on release')
  area = await geometry()
  assert.ok(Math.abs(area.x - area.left - 20) < 1, 'Dragging toward the left snaps to that edge')
  const saved = await run(`localStorage.getItem('liteconnect-ai-task-position-sidebar')`)
  assert.equal(JSON.parse(saved).edge, 'left', 'The dragged position is persisted')
  const dragTo = async (edge, target) => {
    const start = await geometry()
    const point = target(start)
    await mouse('mousePressed', start.x, start.y, { button: 'left', buttons: 1, clickCount: 1 })
    await mouse('mouseMoved', point.x, point.y, { button: 'left', buttons: 1 })
    await mouse('mouseReleased', point.x, point.y, { button: 'left', buttons: 0, clickCount: 1 })
    await settle()
    assert.equal(await run(`document.querySelector('.ai-background-tasks').dataset.edge`), edge, `Dragging docks to the ${edge} edge`)
    assert.equal(JSON.parse(await run(`localStorage.getItem('liteconnect-ai-task-position-sidebar')`)).edge, edge, `The ${edge} edge is persisted`)
    await openTasks()
    assert.ok(await run(`(() => {const p=document.querySelector('.background-popover').getBoundingClientRect(),a=document.querySelector('.ai-background-tasks').getBoundingClientRect();return p.left>=a.left&&p.right<=a.right&&p.top>=a.top&&p.bottom<=a.bottom})()`), `${edge}: expanded card stays inside the chat`)
    await run(`document.querySelector('.background-heading-toggle').click()`)
    await wait(`!document.querySelector('.background-popover')`)
  }
  await dragTo('top', a => ({ x: (a.left+a.right)/2, y: a.top+20 }))
  await dragTo('right', a => ({ x: a.right-20, y: (a.top+a.bottom)/2 }))
  await dragTo('bottom', a => ({ x: (a.left+a.right)/2, y: a.bottom-20 }))
  await dragTo('left', a => ({ x: a.left+20, y: a.top+35 }))
  await openTasks()
  await run(`document.querySelector('.composer-input').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`)
  await wait(`!document.querySelector('.background-popover')`)
  await run(`Object.assign(document.querySelector('${panel}').style,{width:'300px',height:'420px'})`)
  await settle()
  area = await geometry()
  assert.ok(area.x>=area.left+20&&area.x<=area.right-20&&area.y>=area.top+20&&area.y<=area.bottom-20, 'Resizing keeps the icon inside its bounds')
  await openTasks()
  assert.ok(await run(`(() => {const p=document.querySelector('.background-popover').getBoundingClientRect(),a=document.querySelector('.ai-background-tasks').getBoundingClientRect();return p.left>=a.left&&p.right<=a.right&&p.top>=a.top&&p.bottom<=a.bottom})()`), 'A dragged icon opens a bounded popover in a short narrow panel')
  await run(`window.__uiRegression.closeImageComposer()`)
  assert.equal(await run(`!!document.querySelector('.background-float-trigger')`), false, 'Closing AI removes its floating task UI')
  await run(`window.__uiRegression.openImageComposer()`)
  await wait(`!!document.querySelector('.background-float-trigger')`)
  await settle()
  area = await geometry()
  assert.ok(Math.abs(area.x-area.left-20)<1, 'Reopening restores the saved edge')
  assert.equal(await run(`!!document.querySelector('.background-popover')`), false, 'Reopening AI starts with the tasks collapsed')

  // Freeze real browser animations at specific frames to inspect the morph.
  await run(`Object.assign(document.querySelector('${panel}').style,{width:'440px',height:'620px'})`)
  await settle()
  const freeze = async time => {
    await run(`document.querySelector('.background-popover').getAnimations({subtree:true}).forEach(animation=>{animation.pause();animation.currentTime=${time}})`)
    await settle()
  }
  const screenshot = async name => {
    await run(`document.querySelector('${panel}').scrollIntoView({block:'start'})`)
    const rect = await run(`(() => {const r=document.querySelector('${panel}').getBoundingClientRect();return {x:Math.floor(r.x),y:Math.floor(r.y),width:Math.floor(r.width),height:Math.floor(r.height)}})()`)
    fs.writeFileSync(path.join(artifacts, name), (await window.webContents.capturePage(rect)).toPNG())
  }
  await screenshot('morph-closed.png')
  await run(`document.querySelector('.background-float-trigger').click()`)
  await settle()
  await freeze(0)
  assert.ok(await run(`(() => {const p=document.querySelector('.background-popover').getBoundingClientRect(),b=document.querySelector('.background-float-trigger').getBoundingClientRect();return Math.abs(p.x-b.x)<1&&Math.abs(p.y-b.y)<1&&Math.abs(p.width-40)<1&&Math.abs(p.height-40)<1&&getComputedStyle(document.querySelector('.background-task-body')).opacity==='0'})()`), 'Opening starts at the exact circle bounds with task text hidden')
  await screenshot('morph-start.png')
  await freeze(110)
  assert.ok(await run(`(() => {const p=document.querySelector('.background-popover'),body=p.querySelector('.background-task-body');return p.getBoundingClientRect().width>40&&p.getBoundingClientRect().width<420&&+getComputedStyle(body).opacity>0&&+getComputedStyle(body).opacity<1&&getComputedStyle(body).transform==='none'})()`), 'Mid-morph content fades without scaling the command text')
  await screenshot('morph-middle.png')
  await run(`document.querySelector('.background-popover').getAnimations({subtree:true}).forEach(animation=>animation.finish())`)
  await wait(`!document.querySelector('.background-popover').getAnimations({subtree:true}).length`)
  await screenshot('morph-open.png')
  await run(`document.querySelector('.background-heading > button').click()`)
  await settle()
  await freeze(90)
  assert.ok(await run(`!document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})&&document.querySelector('.background-popover').inert`), 'The circle stays hidden and closing content cannot be activated')
  await screenshot('morph-closing.png')
  await run(`document.querySelector('.background-float-trigger').click()`)
  await openTasks()
  assert.ok(await run(`document.querySelectorAll('.background-popover').length===1&&!document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})`), 'Reopening during collapse ends in one stable card')
  await run(`document.querySelector('.background-heading > button').click()`)
  await wait(`!document.querySelector('.background-popover')`)
  await run(`document.querySelector('.background-float-trigger').click()`)
  await settle()
  await run(`window.__uiRegression.setBackgroundLayout(false,false)`)
  await wait(`!document.querySelector('.background-popover')`)
  assert.ok(await run(`!document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})`), 'Leaving AI cancels an in-progress morph')
  await run(`window.__uiRegression.setBackgroundLayout(false,true)`)
  await wait(`document.querySelector('.background-float-trigger').checkVisibility({visibilityProperty:true})`)
  assert.equal(await run(`!!document.querySelector('.background-popover')`), false, 'Returning after an interrupted morph restores the collapsed circle')
  await window.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await openTasks()
  assert.equal(await run(`document.querySelector('.background-popover').getAnimations({subtree:true}).length`), 0, 'Reduced-motion preference skips the morph')
  await run(`document.querySelector('.background-heading > button').click()`)
  await wait(`!document.querySelector('.background-popover')`)
  await window.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [] })
  await run(`window.__uiRegression.setBackgroundJobs([])`)
  await wait(`!document.querySelector('.ai-background-tasks')`)
  assert.equal(await run('window.__uiError || null'), null)
  console.log(JSON.stringify({ passed: true, layoutCases: 12, flows: ['live elapsed time', 'collapsed overview', 'no IPC polling', 'fixed terminal durations', 'hide/return/close', 'popover bounds', 'pointer drag and edge snap', 'position persistence', 'Escape and outside dismissal', 'failure badge', 'circle/card morph frames', 'rapid reversal and interruption', 'reduced motion'], artifacts }))
  clearTimeout(timeout)
  window.destroy()
  app.quit()
}).catch(error => { console.error(error, { artifacts }); clearTimeout(timeout); if (window) window.destroy(); app.exit(1) })
