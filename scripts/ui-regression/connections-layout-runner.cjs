const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'liteconnect-connections-layout-'))
app.setPath('userData', path.join(artifacts, 'profile'))
let action = 'load'
const watchdog = setTimeout(() => { console.error('Timed out', { action, artifacts }); app.exit(1) }, 180_000)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1280, height: 900, webPreferences: { backgroundThrottling: false } })
  const run = source => { action = source.slice(0, 180); return win.webContents.executeJavaScript(source) }
  const wait = async source => {
    const until = Date.now() + 10000
    while (!await run(source)) {
      if (Date.now() > until) throw new Error('Timeout: ' + source + '; ' + await run('window.__perfError || ""'))
      await new Promise(resolve => setTimeout(resolve, 35))
    }
  }
  const settle = () => run('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  const click = selector => run('document.querySelector(' + JSON.stringify(selector) + ').click()')
  const input = (selector, value) => run('(()=>{const e=document.querySelector(' + JSON.stringify(selector) + ');e.value=' + JSON.stringify(value) + ';e.dispatchEvent(new Event("input",{bubbles:true}))})()')
  const screenshot = async name => { await settle(); fs.writeFileSync(path.join(artifacts, name), (await win.webContents.capturePage()).toPNG()) }
  await win.loadURL(process.env.LITECONNECT_UI_TEST_URL)
  await wait('!!window.__perf')
  await run('window.__perf.mountAppearance()')
  await settle()
  assert.equal(await run('document.querySelector(".group-panel-title").textContent'), '导航')
  assert.equal(await run('document.querySelector(".page-title").textContent'), '默认分组')
  assert.equal(await run('document.querySelector(".page-result-count").textContent'), '5 个连接')
  assert.equal(await run('document.querySelector(".smart-item[data-view=all] .group-count").textContent'), '6')
  assert.equal(await run('document.querySelector(".search-scope")'), null, 'Navigation selects the scope without a duplicate selector')
  assert.ok(await run('document.querySelector(".group-search-input").placeholder.startsWith("定位")'))
  assert.ok(await run('document.querySelector(".search-input").placeholder.startsWith("筛选当前列表")'))
  assert.equal(await run('document.querySelectorAll(".filter-chips").length'), 0)
  assert.equal(await run('document.querySelectorAll(".tag-filter-menu").length'), 0)
  assert.equal(await run('document.querySelector(".connection-row:not(.has-color-tag) .color-tag")'), null, 'Untagged connections have no status-like gray dot')
  assert.equal(await run('document.querySelectorAll(".color-tag").length'), 3, 'Explicit gray and other assigned colors stay visible')
  assert.equal(await run('document.querySelectorAll(".sidebar-conn-dot").length'), 3)
  assert.equal(await run('document.querySelector(".conn-meta .conn-stats")'), null)
  assert.ok(await run('document.querySelector(".conn-stats").title.includes("2026") && !document.querySelector(".conn-stats").textContent.includes("14:31")'), 'Full timestamps stay available in the usage tooltip')
  assert.ok(await run('document.querySelector(".conn-stats").textContent.includes("最近连接")'), 'The short date explains what it represents')
  assert.ok(await run('(()=>{const row=document.querySelector(".connection-row"),name=row.querySelector(".conn-name").getBoundingClientRect(),stats=row.querySelector(".conn-stats").getBoundingClientRect(),actions=row.querySelector(".row-actions").getBoundingClientRect();return stats.left-name.right<=16 && stats.right<actions.left-40})()'), 'Usage information stays beside the name in the left information area')
  assert.ok(await run('document.querySelector(".conn-note").textContent.includes("测试备注")'))
  const initialMainCount = await run('document.querySelectorAll(".connection-row").length')
  await input('.group-search-input', '备份')
  assert.equal(await run('document.querySelectorAll(".connection-row").length'), initialMainCount, 'Navigation search does not filter the right list')
  await input('.group-search-input', '')

  await click('.tag-filter .dropdown-trigger')
  await wait('!!document.querySelector(".tag-filter-menu [aria-checked=true]")')
  assert.equal(await run('document.querySelector(".tag-filter-menu [aria-checked=true]").dataset.value'), '')
  await run('document.activeElement.dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowDown",bubbles:true,cancelable:true}))')
  assert.equal(await run('document.activeElement.dataset.value'), 'gray')
  await run('document.activeElement.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true,cancelable:true}))')
  await wait('!document.querySelector(".tag-filter-menu") && document.activeElement===document.querySelector(".tag-filter .dropdown-trigger")')
  await click('.tag-filter .dropdown-trigger')
  await click('.tag-filter-menu [data-value=blue]')
  await wait('document.querySelectorAll(".connection-row").length===1 && !!document.querySelector(".active-tag")')
  assert.ok(await run('document.querySelector(".active-tag").textContent.includes("蓝")'))
  await input('.search-input', '10.')
  await click('.active-tag-clear')
  await wait('document.querySelectorAll(".connection-row").length===5')
  assert.equal(await run('document.querySelector(".search-input").value'), '10.', 'Clearing a tag keeps the search query')
  await click('.search-clear')
  await click('.tag-filter .dropdown-trigger')
  await settle()
  await run('document.body.dispatchEvent(new PointerEvent("pointerdown",{bubbles:true}))')
  await wait('!document.querySelector(".tag-filter-menu")')

  await input('.search-input', '云服务器')
  assert.equal(await run('document.querySelectorAll(".connection-row").length'), 0)
  await click('.smart-item[data-view=all]')
  await wait('document.querySelectorAll(".connection-row").length===1')
  assert.equal(await run('document.querySelector(".page-title").textContent'), '全部连接')
  assert.equal(await run('document.querySelector(".page-result-count").textContent'), '显示 1 / 6')
  assert.equal(await run('document.querySelectorAll(".group-item.active").length'), 0)
  assert.equal(await run('document.querySelector(".search-input").value'), '云服务器', 'Switching scope preserves the query')
  assert.equal(await run('document.querySelector(".conn-group").title'), '腾讯云')
  await run('document.querySelector(".search-input").dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",bubbles:true,cancelable:true}))')
  assert.equal(await run('window.__perf.connects.at(-1)'), 'archive-host', 'Global results remain keyboard-connectable')
  await click('.search-clear')
  await click('.group-block[data-group-id=servers] > .group-item')
  assert.equal(await run('document.querySelectorAll(".connection-row").length'), 5)
  assert.ok(await run('!!document.querySelector(".group-item.active") && !document.querySelector(".smart-item.active")'), 'Returning to the same group restores selection')
  assert.equal(await run('document.querySelector(".group-item.active .collapse-btn").getAttribute("aria-expanded")'), 'true')

  await click('.sort-control .dropdown-trigger')
  await click('.sort-menu [data-value=recent]')
  await wait('window.__perf.settings().connectionSortMode==="recent"')
  assert.equal(await run('document.querySelector(".sort-control").dataset.value'), 'recent')
  await click('.sort-control .dropdown-trigger')
  await click('.sort-menu [data-value=manual]')
  await wait('window.__perf.settings().connectionSortMode==="manual"')
  await click('.smart-item[data-view=recent]')
  assert.equal(await run('document.querySelector(".page-title").textContent'), '最近连接')
  assert.equal(await run('document.querySelector(".sort-control").dataset.value'), 'recent')
  await click('.sort-control .dropdown-trigger')
  assert.equal(await run('document.querySelector(".sort-menu [data-value=manual]").disabled'), true)
  assert.equal(await run('window.__perf.settings().connectionSortMode'), 'manual', 'The recent view does not overwrite the saved sort preference')
  await run('document.activeElement.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true,cancelable:true}))')
  await click('.group-block[data-group-id=servers] > .group-item')
  assert.equal(await run('document.querySelector(".sort-control").dataset.value'), 'manual')
  await click('.toolbar-more-button')
  await wait('!!document.querySelector(".toolbar-menu")')
  assert.equal(await run('document.querySelectorAll(".toolbar-menu button").length'), 4)
  await click('.toolbar-menu [data-value=credentials]')
  await wait('!!document.querySelector(".credential-modal")')
  await click('.credential-modal .ui-modal-close')
  await wait('!document.querySelector(".credential-modal")')

  const layoutCases = []
  for (const theme of ['light', 'dark', 'eyecare']) {
    await run('document.documentElement.dataset.theme=' + JSON.stringify(theme))
    for (const compact of [false, true]) {
      await run('document.querySelectorAll(".density-switch button")[' + Number(compact) + '].click()')
      for (const width of [1280, 960, 720]) {
        win.setContentSize(width, 900)
        await settle()
        const state = await run('(()=>{const row=document.querySelector(".connection-row"),r=row.getBoundingClientRect();return {pageOverflow:document.documentElement.scrollWidth>innerWidth,overflow:row.scrollWidth>row.clientWidth+1,actions:[...row.querySelectorAll(".secondary-action")].filter(e=>getComputedStyle(e).display!=="none").map(e=>({opacity:getComputedStyle(e).opacity,events:getComputedStyle(e).pointerEvents,right:e.getBoundingClientRect().right})),hintVisible:!!document.querySelector(".list-keyboard-hint").getClientRects().length,rowRight:r.right,nameWidth:row.querySelector(".conn-name-text").getBoundingClientRect().width}})()')
        assert.ok(!state.pageOverflow && !state.overflow && state.hintVisible && state.nameWidth > 10, JSON.stringify({ theme, width, compact, state }))
        assert.equal(state.actions.length, compact ? 1 : 4, 'Each density keeps its existing always-visible actions')
        assert.ok(state.actions.every(e => e.opacity === '1' && e.events !== 'none' && e.right <= state.rowRight + 1))
        if (!compact && width === 1280) {
          assert.ok(await run('(()=>{const a=[...document.querySelectorAll(".conn-addr")].at(-1);return a.scrollWidth<=a.clientWidth+1})()'), 'Long notes do not squeeze the host address')
        }
        const searchWidth = await run('document.querySelector(".search-input").getBoundingClientRect().width')
        await input('.search-input', '10.')
        await settle()
        const clearLayout = await run('(()=>{const clear=document.querySelector(".clear-filters"),c=clear.getBoundingClientRect(),r=document.querySelector(".page-result-count").getBoundingClientRect(),main=document.querySelector(".connections-main").getBoundingClientRect();return {nearResult:clear.parentElement===document.querySelector(".page-title-row")&&c.left-r.right<=12,aligned:Math.abs(c.top+c.height/2-r.top-r.height/2)<5,bounded:c.left>=main.left&&c.right<=main.right,searchWidth:document.querySelector(".search-input").getBoundingClientRect().width,insideControls:!!document.querySelector(".filter-bar .clear-filters")}})()')
        assert.ok(clearLayout.nearResult && clearLayout.aligned && clearLayout.bounded && !clearLayout.insideControls && Math.abs(clearLayout.searchWidth - searchWidth) < 1, JSON.stringify({ theme, compact, width, clearLayout, searchWidth }))
        if (theme === 'light' && !compact && width === 1280) await screenshot('connections-clear-filters.png')
        await click('.clear-filters')
        await wait('!document.querySelector(".clear-filters") && document.querySelector(".search-input").value===""')
        layoutCases.push({ theme, compact, width })
        if (width === 1280 && !compact) await screenshot('connections-' + theme + '.png')
        if (width === 720 && compact && theme === 'light') await screenshot('connections-compact-720.png')
      }
    }
  }
  await run('document.querySelector(".density-switch button").click();window.__perf.locale("en-US")')
  win.setContentSize(1280, 900)
  await settle()
  assert.equal(await run('document.querySelector(".group-panel-title").textContent'), 'Navigation')
  assert.ok(await run('document.querySelector(".tag-filter .dropdown-trigger").textContent.includes("Filter by tag")'))
  await click('.tag-filter .dropdown-trigger')
  assert.equal(await run('document.querySelector(".tag-filter-menu [data-value=blue] .dropdown-label").textContent'), 'Blue')
  await click('.tag-filter-menu [data-value=""]')
  await click('.smart-item[data-view=all]')
  assert.equal(await run('document.querySelector(".page-title").textContent'), 'All connections')
  assert.ok(await run('document.querySelector(".search-input").placeholder.startsWith("Search all connections")'))
  await screenshot('connections-en.png')
  await click('.tag-filter .dropdown-trigger')
  await click('.tag-filter-menu [data-value=blue]')
  await input('.search-input', '10.')
  await click('.clear-filters')
  await wait('!document.querySelector(".active-tag") && document.querySelector(".search-input").value===""')
  assert.equal(await run('document.querySelectorAll(".connection-row").length'), 6, 'Clear filters removes both the tag and the query without changing navigation scope')
  assert.equal(await run('window.__perfError || null'), null)
  console.log(JSON.stringify({ passed: true, layoutCases, artifacts }))
  clearTimeout(watchdog); win.destroy(); app.quit()
}).catch(error => { console.error(error, { action, artifacts }); clearTimeout(watchdog); app.exit(1) })
