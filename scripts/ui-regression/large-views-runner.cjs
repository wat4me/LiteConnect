const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'liteconnect-large-views-'))
app.setPath('userData', path.join(artifacts, 'profile'))
let action = ''
const watchdog = setTimeout(() => { console.error('Timed out', { action, artifacts }); app.exit(1) }, 180_000)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1100, height: 800, webPreferences: { backgroundThrottling: false } })
  const run = source => { action = source.slice(0, 220); return win.webContents.executeJavaScript(source) }
  const wait = async source => {
    const until = Date.now() + 15000
    while (!await run(source)) {
      if (Date.now() > until) throw new Error('Timeout: ' + source + '; error: ' + await run('window.__largeError || null'))
      await new Promise(resolve => setTimeout(resolve, 40))
    }
  }
  const settle = () => run('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  const click = selector => run('document.querySelector(' + JSON.stringify(selector) + ').click()')
  const input = (selector, value) => run('(()=>{const el=document.querySelector(' + JSON.stringify(selector) + ');el.value=' + JSON.stringify(value) + ';el.dispatchEvent(new Event("input",{bubbles:true}))})()')
  const metrics = {}
  await win.loadURL(process.env.LITECONNECT_UI_TEST_URL)
  await wait('!!window.__large')
  // Default file paging, then show every loaded file without mounting 5000 rows.
  await run('document.querySelector(".sftp-dir-tree").scrollTop=100000')
  await settle()
  await click('.tree-more-btn:last-child')
  await settle()
  metrics.sftp = await run('document.querySelectorAll(".tree-row").length')
  assert.ok(metrics.sftp > 0 && metrics.sftp < 60)
  assert.equal(await run('document.querySelector(".sftp-dir-tree .virtual-list").dataset.itemCount'), '5000')
  await run('document.querySelector(".sftp-dir-tree").scrollTop=0')
  await settle()
  await click('.tree-row.file')
  await run('document.querySelector(".sftp-dir-tree").scrollTop=10000000')
  await settle()
  // Select the last actual file with Shift across the unmounted middle rows.
  await run('(()=>{const files=document.querySelectorAll(".tree-row.file");files[files.length-1].dispatchEvent(new MouseEvent("click",{bubbles:true,shiftKey:true}))})()')
  await click('.file-selection-actions button:first-child')
  assert.equal(await run('window.__large.downloads.at(-1).length'), 5000, 'Shift selection and batch download include offscreen files')
  await run('document.querySelector(".sftp-explorer").dispatchEvent(new KeyboardEvent("keydown",{key:"f",ctrlKey:true,bubbles:true,cancelable:true}))')
  await input('.file-search-input', 'file-04999')
  await wait('document.querySelectorAll(".tree-row.file").length===1')
  assert.ok(await run('document.querySelector(".tree-name").textContent.includes("04999")'))
  await input('.file-search-input', 'file-')
  await settle()
  assert.ok(await run('document.querySelectorAll(".tree-row.file").length < 60'))
  await run('window.__large.dirs(true)')
  await run('window.__large.locate("/file-04999")')
  await wait('!!document.querySelector(".tree-row.current")')
  await settle()
  assert.ok(await run('(()=>{const r=document.querySelector(".tree-row.current").getBoundingClientRect(),s=document.querySelector(".sftp-dir-tree").getBoundingClientRect();return r.top>=s.top-2&&r.bottom<=s.bottom+2})()'), 'Follow/locate reveals an offscreen directory')
  await run('document.querySelector(".sftp-explorer").dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowUp",bubbles:true,cancelable:true}))')
  await settle()
  assert.ok(await run('document.querySelector(".tree-row.focused").textContent.includes("04998")'), 'Keyboard focus crosses virtual windows')
  fs.writeFileSync(path.join(artifacts, 'sftp.png'), (await win.webContents.capturePage()).toPNG())

  await run('window.__large.view("database")')
  await settle()
  metrics.database = await run('document.querySelectorAll("tbody tr[data-row-index]").length')
  assert.ok(metrics.database > 0 && metrics.database < 60)
  assert.ok(await run('!!document.querySelector("td.nul") && !!document.querySelector("td.blob")'))
  const widths = await run('[...document.querySelectorAll("thead th")].map(el=>el.getBoundingClientRect().width)')
  await run('document.querySelector(".grid-scroll").scrollTop=10000000')
  await wait('!!document.querySelector("[data-row-index=\\"4999\\"]")')
  assert.equal(await run('document.querySelector("[data-row-index=\\"4999\\"] .rn").textContent'), '5100')
  assert.deepEqual(await run('[...document.querySelectorAll("thead th")].map(el=>el.getBoundingClientRect().width)'), widths, 'Column widths stay stable while scrolling')
  assert.ok(await run('(()=>{const h=document.querySelector("thead th").getBoundingClientRect(),s=document.querySelector(".grid-scroll").getBoundingClientRect();return Math.abs(h.top-s.top)<2})()'), 'Sticky header remains visible')
  await run('document.querySelector("[data-row-index=\\"4999\\"] td:nth-child(4)").dispatchEvent(new MouseEvent("dblclick",{bubbles:true}))')
  assert.deepEqual(await run('window.__large.copied.at(-1)'), { index: 4999, text: '内容'.repeat(19) })
  await click('thead th.sortable')
  await settle()
  assert.equal(await run('document.querySelector("tbody tr[data-row-index] td:nth-child(2)").textContent.trim()'), '4999')
  assert.equal(await run('document.querySelector(".grid-scroll").scrollTop'), 0)
  await run('window.__large.filter("record-4999")')
  await settle()
  assert.equal(await run('document.querySelectorAll("tbody tr[data-row-index]").length'), 1)
  assert.equal(await run('window.__large.csv().split("\\r\\n").length'), 2)
  await run('window.__large.filter("")')
  await settle()
  assert.equal(await run('window.__large.csv().split("\\r\\n").length'), 5001, 'Export keeps all logical rows')
  await run('document.querySelector(".large-fixture").style.setProperty("--db-font-size","18px")')
  await settle()
  await run('document.querySelector(".grid-scroll").scrollTop=10000000')
  await wait('!!document.querySelector("[data-row-index=\\"4999\\"]")')
  await settle()
  assert.ok(await run('(()=>{const r=document.querySelector("[data-row-index=\\"4999\\"]").getBoundingClientRect(),s=document.querySelector(".grid-scroll").getBoundingClientRect();return r.top>=s.top && r.bottom<=s.bottom+2})()'), 'Font-size changes keep the last row reachable')
  fs.writeFileSync(path.join(artifacts, 'database.png'), (await win.webContents.capturePage()).toPNG())

  await run('window.__large.view("logs");window.__large.append(10000)')
  const atBottom = '(()=>{const el=document.querySelector(".logs-scroll");return el.scrollHeight-el.scrollTop-el.clientHeight<2})()'
  await wait(atBottom)
  await settle()
  metrics.logs = await run('document.querySelectorAll(".log-line").length')
  assert.ok(metrics.logs > 0 && metrics.logs < 90)
  await input('.logs-search', 'line-10000')
  await wait('!!document.querySelector(".log-line-active")')
  assert.ok(await run('document.querySelector(".log-line-active").textContent.includes("line-10000")'))
  await run('window.__large.append(5)')
  await settle()
  assert.ok(await run('document.querySelector(".log-line-active").textContent.includes("line-10000")'), 'Search stays on the same sequence during buffer rotation')
  await click('.logs-actions button:last-child')
  await wait('window.__large.copied.length===2')
  assert.equal(await run('window.__large.copied.at(-1).split("\\n").length'), 10000)
  await click('.logs-search-clear')
  await run('document.querySelector(".logs-scroll").scrollTop=40000')
  await settle()
  const anchor = await run('(()=>{const s=document.querySelector(".logs-scroll").getBoundingClientRect();const e=[...document.querySelectorAll(".log-line")].find(e=>e.getBoundingClientRect().top>=s.top);return {text:e.textContent,top:e.getBoundingClientRect().top-s.top}})()')
  await run('window.__large.append(30)')
  await settle()
  const anchored = await run('(()=>{const s=document.querySelector(".logs-scroll");const e=[...document.querySelectorAll(".log-line")].find(e=>e.textContent===' + JSON.stringify(anchor.text) + ');return {top:e?e.getBoundingClientRect().top-s.getBoundingClientRect().top:undefined,scroll:s.scrollTop,auto:document.querySelectorAll(".logs-check input")[1].checked,first:document.querySelector(".log-line")?.textContent}})()')
  assert.ok(anchored.top !== undefined && Math.abs(anchored.top - anchor.top) < 2, 'Buffer rotation preserves the visible history line: ' + JSON.stringify({ anchor, anchored }))
  await click('.logs-jump-latest')
  await wait(atBottom)
  await run('window.__large.append(1,true)')
  await settle()
  await wait(atBottom)
  assert.equal(await run('document.querySelectorAll(".logs-check input")[1].checked'), true)
  fs.writeFileSync(path.join(artifacts, 'logs.png'), (await win.webContents.capturePage()).toPNG())
  assert.equal(await run('window.__largeError || null'), null)
  fs.writeFileSync(path.join(artifacts, 'metrics.json'), JSON.stringify(metrics, null, 2))
  console.log(JSON.stringify({ passed: true, metrics, artifacts }))
  clearTimeout(watchdog); win.destroy(); app.quit()
}).catch(error => { console.error(error, { action, artifacts }); clearTimeout(watchdog); app.exit(1) })
